// collectionNames is the reply to listCollections with nameOnly.
func collectionNames(names ...string) bson.D {
	docs := make([]bson.D, 0, len(names))
	for _, name := range names {
		docs = append(docs, bson.D{{Key: "name", Value: name}, {Key: "type", Value: "collection"}})
	}
	return firstBatch(testDatabase+".$cmd.listCollections", docs...)
}

func TestRunAction_loadFixtures(t *testing.T) {
	mt := newMock(t)

	// fixturesDir writes a fixtures folder with two collections and files that are not fixtures.
	fixturesDir := func(t *testing.T) string {
		t.Helper()
		dir := t.TempDir()
		writeFile(t, dir, filepath.Join("fixtures", "cards.yml"), "- _id: c1\n  suit: clubs\n  value: jack\n- _id: c2\n  suit: clubs\n  value: queen\n")
		writeFile(t, dir, filepath.Join("fixtures", "pokemons.yaml"), "- _id: p1\n  name: pikachu\n  types: [electric]\n")
		writeFile(t, dir, filepath.Join("fixtures", "notes.txt"), "not a fixture\n")
		writeFile(t, dir, filepath.Join("fixtures", "archive", "old.yml"), "- _id: o1\n")
		return dir
	}

	mt.Run("drops every non-system collection, then inserts each file into the collection named after it", func(mt *mockT) {
		// AC 4 (#2039): a valid folder behaves as before — system.* kept, every other collection dropped, then one
		// insert per fixture file in directory order (os.ReadDir sorts by name), subfolders and other files skipped.
		dir := fixturesDir(mt.T)
		mt.AddMockResponses(
			collectionNames("decks", "system.views", "cards"),
			successResponse(), // drop decks
			successResponse(), // drop cards
			successResponse(bson.E{Key: "n", Value: 2}), // insert cards.yml
			successResponse(bson.E{Key: "n", Value: 1}), // insert pokemons.yaml
		)

		got, err := testExecutor.runAction(workdirCtx(dir), mt.Client, map[string]any{"type": "loadFixtures", "folder": "fixtures"})
		require.NoError(mt, err)
		assert.Nil(mt, got)

		names, cmds := sentCommands(mt)
		require.Equal(mt, []string{"listCollections", "drop", "drop", "insert", "insert"}, names)
		assert.Equal(mt, true, cmds[0]["nameOnly"])
		assert.Equal(mt, testDatabase, cmds[0]["$db"])
		assert.Equal(mt, "decks", cmds[1]["drop"])
		assert.Equal(mt, "cards", cmds[2]["drop"])
		assert.Equal(mt, "cards", cmds[3]["insert"])
		assert.Equal(mt, bson.A{
			bson.M{"_id": "c1", "suit": "clubs", "value": "jack"},
			bson.M{"_id": "c2", "suit": "clubs", "value": "queen"},
		}, cmds[3]["documents"])
		assert.Equal(mt, "pokemons", cmds[4]["insert"])
		assert.Equal(mt, bson.A{bson.M{"_id": "p1", "name": "pikachu", "types": bson.A{"electric"}}}, cmds[4]["documents"])
	})

	mt.Run("every fixture file is closed once decoded (D113)", func(mt *mockT) {
		// #2039 restructured the fixture reading; its new decoding helper closes each file it opens.
		dir := fixturesDir(mt.T)
		cards := filepath.Join(dir, "fixtures", "cards.yml")
		pokemons := filepath.Join(dir, "fixtures", "pokemons.yaml")
		require.Equal(mt, 0, openHandles(mt.T, cards)+openHandles(mt.T, pokemons))
		mt.AddMockResponses(collectionNames(), successResponse(), successResponse())

		require.NoError(mt, testExecutor.loadFixtures(workdirCtx(dir), mt.Client, map[string]any{"folder": "fixtures"}))
		assert.Equal(mt, 0, openHandles(mt.T, cards))
		assert.Equal(mt, 0, openHandles(mt.T, pokemons))
	})

	mt.Run("no folder is an error before anything is sent", func(mt *mockT) {
		got, err := run(mt, map[string]any{"type": "loadFixtures"})
		assert.EqualError(mt, err, "folder is required")
		assert.Nil(mt, got)
		assert.Empty(mt, mt.GetAllStartedEvents())
	})

	mt.Run("a listCollections error is wrapped", func(mt *mockT) {
		mt.AddMockResponses(serverError())

		err := testExecutor.loadFixtures(workdirCtx(fixturesDir(mt.T)), mt.Client, map[string]any{"folder": "fixtures"})
		assert.EqualError(mt, err, "failed to list collections: "+serverErrorText)
	})

	mt.Run("a drop error is wrapped with the collection and stops the load", func(mt *mockT) {
		mt.AddMockResponses(collectionNames("decks", "cards"), serverError())

		err := testExecutor.loadFixtures(workdirCtx(fixturesDir(mt.T)), mt.Client, map[string]any{"folder": "fixtures"})
		assert.EqualError(mt, err, "failed to drop collection decks: "+serverErrorText)
		names, _ := sentCommands(mt)
		assert.Equal(mt, []string{"listCollections", "drop"}, names)
	})

	mt.Run("a missing folder fails before any collection is dropped", func(mt *mockT) {
		// AC 1 (#2039, D126): the step fails and every collection is still there — not even listed.
		dir := mt.TempDir()

		err := testExecutor.loadFixtures(workdirCtx(dir), mt.Client, map[string]any{"folder": "missing"})
		assert.EqualError(mt, err, "open "+filepath.Join(dir, "missing")+": no such file or directory")
		assert.Empty(mt, mt.GetAllStartedEvents(), "no drop sent")
	})

	mt.Run("a listed fixture that cannot be opened is wrapped with its path, before any drop", func(mt *mockT) {
		// A dangling symlink is listed (it is not a folder and ends in .yml) but os.Open fails on it.
		dir := mt.TempDir()
		path := filepath.Join(dir, "fixtures", "cards.yml")
		require.NoError(mt, os.MkdirAll(filepath.Dir(path), 0o700))
		require.NoError(mt, os.Symlink(filepath.Join(dir, "gone.yml"), path))

		err := testExecutor.loadFixtures(workdirCtx(dir), mt.Client, map[string]any{"folder": "fixtures"})
		assert.EqualError(mt, err, "failed to open file "+path+": open "+path+": no such file or directory")
		assert.Empty(mt, mt.GetAllStartedEvents(), "no drop sent")
	})

	// badAfterGood: AC 2 (#2039, D126): every file is read and checked before the first drop, so the good file is not
	// inserted either — whether the bad one fails to decode or decodes into something that is not a list of documents.
	badAfterGood := []struct {
		name    string
		content string
		want    func(path string) string
	}{
		{
			name:    "an empty file after a good one: nothing is dropped and nothing is inserted",
			content: "",
			want:    func(path string) string { return "failed to decode fixture " + path + ": EOF" },
		},
		{
			name:    "a list of scalars after a good file: nothing is dropped and nothing is inserted",
			content: "- 1\n",
			want:    func(path string) string { return "fixture " + path + ": element 1 is not a document" },
		},
	}
	for _, tt := range badAfterGood {
		mt.Run(tt.name, func(mt *mockT) {
			dir := mt.TempDir()
			writeFile(mt.T, dir, filepath.Join("fixtures", "cards.yml"), "- _id: c1\n")
			path := writeFile(mt.T, dir, filepath.Join("fixtures", "decks.yml"), tt.content)

			err := testExecutor.loadFixtures(workdirCtx(dir), mt.Client, map[string]any{"folder": "fixtures"})
			assert.EqualError(mt, err, tt.want(path))
			assert.Empty(mt, mt.GetAllStartedEvents(), "no listCollections, no drop and no insert sent")
		})
	}

	// decodeErrors fail while the fixtures are read and checked: AC 2 (#2039, D126), no collection was listed or
	// dropped. A file that decodes but holds no documents, or an element that is not a document, fails here too: the
	// driver would refuse it only inside InsertMany, after the drop. Elements are numbered from 1, as a reader counts.
	decodeErrors := []struct {
		name    string
		content string
		want    func(path string) string
	}{
		{
			name:    "an empty fixture file fails to decode before any drop",
			content: "",
			want:    func(path string) string { return "failed to decode fixture " + path + ": EOF" },
		},
		{
			name:    "a fixture that is a mapping, not a list, fails to decode before any drop",
			content: "suit: clubs\n",
			want: func(path string) string {
				return "failed to decode fixture " + path + ": yaml: unmarshal errors:\n  line 1: cannot unmarshal !!map into []interface {}"
			},
		},
		{
			name:    "an empty list holds no documents and fails before any drop",
			content: "[]\n",
			want:    func(path string) string { return "fixture " + path + " holds no documents" },
		},
		{
			name:    "a YAML null holds no documents and fails before any drop",
			content: "~\n",
			want:    func(path string) string { return "fixture " + path + " holds no documents" },
		},
		{
			name:    "a list of scalars fails before any drop",
			content: "- 1\n- 2\n",
			want:    func(path string) string { return "fixture " + path + ": element 1 is not a document" },
		},
		{
			name:    "a list of lists fails before any drop",
			content: "- [a]\n",
			want:    func(path string) string { return "fixture " + path + ": element 1 is not a document" },
		},
		{
			name:    "a mapping with a non-string key is not a document and fails before any drop",
			content: "- 1: a\n",
			want:    func(path string) string { return "fixture " + path + ": element 1 is not a document" },
		},
		{
			// The top level is a document, but the driver cannot encode the mapping nested in it (a non-string key):
			// checked by encoding each document while the fixtures are read, not left to InsertMany after the drop.
			name:    "a document the driver cannot encode fails before any drop",
			content: "- a: {1: b}\n",
			want: func(path string) string {
				return "fixture " + path + ": element 1 is not a document: " + nestedNonStringKeyError
			},
		},
		{
			name:    "a non-document after a document is reported with its position, before any drop",
			content: "- _id: c1\n- ~\n",
			want:    func(path string) string { return "fixture " + path + ": element 2 is not a document" },
		},
	}
	for _, tt := range decodeErrors {
		mt.Run(tt.name, func(mt *mockT) {
			dir := mt.TempDir()
			path := writeFile(mt.T, dir, filepath.Join("fixtures", "cards.yml"), tt.content)

			err := testExecutor.loadFixtures(workdirCtx(dir), mt.Client, map[string]any{"folder": "fixtures"})
			assert.EqualError(mt, err, tt.want(path))
			assert.Empty(mt, mt.GetAllStartedEvents(), "no listCollections, no drop and no insert sent")
		})
	}

	mt.Run("an insert error is wrapped with the collection, after the drop", func(mt *mockT) {
		// The fixture decoded into documents; the server refused them once the database was emptied.
		dir := mt.TempDir()
		writeFile(mt.T, dir, filepath.Join("fixtures", "cards.yml"), "- _id: c1\n")
		mt.AddMockResponses(collectionNames(), serverError())

		err := testExecutor.loadFixtures(workdirCtx(dir), mt.Client, map[string]any{"folder": "fixtures"})
		assert.EqualError(mt, err, "failed to insert documents in collection cards: "+serverErrorText)
		names, _ := sentCommands(mt)
		assert.Equal(mt, []string{"listCollections", "insert"}, names)
	})
}

func TestRunAction_invalidInput(t *testing.T) {
	// Every one of these fails while the action is decoded or its JSON parsed: nothing reaches the server.
	tests := []struct {
		name   string
		action map[string]any
		want   string
	}{
		{name: "count: a filter that is not a string", action: map[string]any{"type": "count", "filter": map[string]any{"suit": "clubs"}},
			want: "'Filter' expected type 'string', got unconvertible type 'map[string]interface {}'"},
		{name: "count: a limit given as a string", action: map[string]any{"type": "count", "options": map[string]any{"limit": "5"}},
			want: "'Options.Limit' expected type 'int64', got unconvertible type 'string'"},
		{name: "count: a filter that is not JSON", action: map[string]any{"type": "count", "filter": "{suit:"}},
		{name: "insert: documents that are not strings", action: map[string]any{"type": "insert", "documents": []any{map[string]any{"suit": "clubs"}}},
			want: "'Documents[0]' expected type 'string', got unconvertible type 'map[string]interface {}'"},
		{name: "insert: a document that is not JSON", action: map[string]any{"type": "insert", "documents": []string{"{suit:"}}},
		{name: "find: a filter that is not JSON", action: map[string]any{"type": "find", "filter": "{suit:"}},
		{name: "find: a sort that is not JSON", action: map[string]any{"type": "find", "options": map[string]any{"sort": "{_id:"}}},
		{name: "find: a projection that is not JSON", action: map[string]any{"type": "find", "options": map[string]any{"projection": "{value:"}}},
		{name: "find: a skip given as a string", action: map[string]any{"type": "find", "options": map[string]any{"skip": "1"}},
			want: "'Options.Skip' expected type 'int64', got unconvertible type 'string'"},
		{name: "update: a filter that is not JSON", action: map[string]any{"type": "update", "filter": "{suit:"}},
		{name: "update: an update that is not JSON", action: map[string]any{"type": "update", "update": "{$set:"}},
		{name: "update: an upsert given as a string", action: map[string]any{"type": "update", "options": map[string]any{"upsert": "true"}},
			want: "'Options.Upsert' expected type 'bool', got unconvertible type 'string'"},
		{name: "delete: a filter that is not JSON", action: map[string]any{"type": "delete", "filter": "{suit:"}},
		{name: "delete: a filter that is not a string", action: map[string]any{"type": "delete", "filter": 42},
			want: "'Filter' expected type 'string', got unconvertible type 'int'"},
		{name: "aggregate: a stage that is not JSON", action: map[string]any{"type": "aggregate", "pipeline": []string{`{"$match":{}}`, "{$group:"}}},
		{name: "aggregate: a pipeline that is one string, not a list", action: map[string]any{"type": "aggregate", "pipeline": `{"$match":{}}`},
			want: "'Pipeline': source data must be an array or slice, got string"},
		{name: "loadFixtures: a folder that is not a string", action: map[string]any{"type": "loadFixtures", "folder": []string{"a"}},
			want: "'Folder' expected type 'string', got unconvertible type '[]string'"},
	}

	mt := newMock(t)
	for _, tt := range tests {
		mt.Run(tt.name, func(mt *mockT) {
			got, err := run(mt, tt.action)
			require.Error(mt, err)
			if tt.want != "" {
				assert.Contains(mt, err.Error(), tt.want)
			}
			assert.Nil(mt, got)
			assert.Empty(mt, mt.GetAllStartedEvents(), "nothing is sent")
		})
	}
}

