// Characterisation tests of the client-bound actions, against the driver's mock deployment (mongo_helpers_test.go).
// Each case pins the command that reaches the wire, the result map Run would put in Result.Actions, and the errors.

// run runs one action of testExecutor on the mock client.
func run(mt *mockT, action map[string]any) (map[string]any, error) {
	mt.Helper()
	return testExecutor.runAction(context.Background(), mt.Client, action)
}

func TestRunAction_count(t *testing.T) {
	mt := newMock(t)

	mt.Run("filter and limit become a $match and a $limit before the $group", func(mt *mockT) {
		mt.AddMockResponses(firstBatch(testNamespace, bson.D{{Key: "_id", Value: 1}, {Key: "n", Value: 3}}))

		got, err := run(mt, map[string]any{"type": "count", "filter": `{"suit":"hearts"}`, "options": map[string]any{"limit": 5}})
		require.NoError(mt, err)
		assert.Equal(mt, map[string]any{"count": int64(3)}, got)

		name, cmd := sentCommand(mt)
		assert.Equal(mt, "aggregate", name)
		assert.Equal(mt, testCollection, cmd["aggregate"])
		assert.Equal(mt, testDatabase, cmd["$db"])
		assert.Equal(mt, bson.A{
			bson.M{"$match": bson.M{"suit": "hearts"}},
			bson.M{"$limit": int64(5)},
			bson.M{"$group": bson.M{"_id": int32(1), "n": bson.M{"$sum": int32(1)}}},
		}, cmd["pipeline"])
	})

	mt.Run("no filter matches everything; no matching document is a count of 0", func(mt *mockT) {
		mt.AddMockResponses(firstBatch(testNamespace))

		got, err := run(mt, map[string]any{"type": "count"})
		require.NoError(mt, err)
		assert.Equal(mt, map[string]any{"count": int64(0)}, got)

		_, cmd := sentCommand(mt)
		assert.Equal(mt, bson.A{
			bson.M{"$match": bson.M{}},
			bson.M{"$group": bson.M{"_id": int32(1), "n": bson.M{"$sum": int32(1)}}},
		}, cmd["pipeline"])
	})

	mt.Run("a server error is returned as is", func(mt *mockT) {
		mt.AddMockResponses(serverError())

		got, err := run(mt, map[string]any{"type": "count"})
		assert.EqualError(mt, err, serverErrorText)
		assert.Nil(mt, got)
	})
}

func TestRunAction_insert(t *testing.T) {
	mt := newMock(t)

	mt.Run("the file's documents go first, then the inline ones; InsertedIDs keeps that order", func(mt *mockT) {
		dir := mt.TempDir()
		writeFile(mt.T, dir, filepath.Join("fixtures", "cards.jsonlist"),
			`{"_id":{"$oid":"5d505646cf6d4fe581014ab2"},"value":"ace"}`+"\n"+`{"_id":"from-file-2","value":"two"}`)
		mt.AddMockResponses(successResponse(bson.E{Key: "n", Value: 4}))

		action := map[string]any{
			"type":      "insert",
			"file":      "fixtures/cards.jsonlist",
			"documents": []string{`{"_id":"inline-1","value":"queen"}`, `{"value":"king"}`},
		}
		got, err := testExecutor.runAction(workdirCtx(dir), mt.Client, action)
		require.NoError(mt, err)

		oid, err := bson.ObjectIDFromHex("5d505646cf6d4fe581014ab2")
		require.NoError(mt, err)
		// mapstructure turns *mongo.InsertManyResult into its field name; a document without _id gets one generated by
		// the driver, so its ObjectID is only checked for its type.
		require.Len(mt, got, 1)
		ids, ok := got["InsertedIDs"].([]any)
		require.Truef(mt, ok, "InsertedIDs is %T", got["InsertedIDs"])
		require.Len(mt, ids, 4)
		assert.Equal(mt, []any{oid, "from-file-2", "inline-1"}, ids[:3])
		generated, ok := ids[3].(bson.ObjectID)
		require.Truef(mt, ok, "generated _id is %T", ids[3])

		name, cmd := sentCommand(mt)
		assert.Equal(mt, "insert", name)
		assert.Equal(mt, testCollection, cmd["insert"])
		assert.Equal(mt, true, cmd["ordered"])
		assert.Equal(mt, bson.A{
			bson.M{"_id": oid, "value": "ace"},
			bson.M{"_id": "from-file-2", "value": "two"},
			bson.M{"_id": "inline-1", "value": "queen"},
			bson.M{"_id": generated, "value": "king"},
		}, cmd["documents"])
	})

	mt.Run("no file and no documents is the driver's empty-slice error, nothing is sent", func(mt *mockT) {
		got, err := run(mt, map[string]any{"type": "insert"})
		require.ErrorIs(mt, err, mongo.ErrEmptySlice)
		assert.Nil(mt, got)
		assert.Empty(mt, mt.GetAllStartedEvents())
	})

	mt.Run("a write error is returned as a BulkWriteException", func(mt *mockT) {
		mt.AddMockResponses(writeErrorsResponse(writeError{Index: 0, Code: 11000, Message: "duplicate key"}))

		got, err := run(mt, map[string]any{"type": "insert", "documents": []string{`{"_id":"dup"}`}})
		var bulkErr mongo.BulkWriteException
		require.ErrorAs(mt, err, &bulkErr)
		assert.True(mt, mongo.IsDuplicateKeyError(err))
		assert.Nil(mt, got)
	})

	mt.Run("a missing file fails before anything is sent", func(mt *mockT) {
		got, err := testExecutor.runAction(workdirCtx(mt.TempDir()), mt.Client,
			map[string]any{"type": "insert", "file": "missing.json", "documents": []string{`{"value":"ace"}`}})
		require.Error(mt, err)
		assert.Nil(mt, got)
		assert.Empty(mt, mt.GetAllStartedEvents())
	})
}

func TestRunAction_find(t *testing.T) {
	mt := newMock(t)

	mt.Run("filter, limit, skip, sort and projection all reach the find command", func(mt *mockT) {
		mt.AddMockResponses(firstBatch(testNamespace,
			bson.D{{Key: "_id", Value: "c1"}, {Key: "stats", Value: bson.D{{Key: "hp", Value: 35}}}, {Key: "types", Value: bson.A{"electric", 1}}},
			bson.D{{Key: "_id", Value: "c2"}},
		))

		got, err := run(mt, map[string]any{
			"type":    "find",
			"filter":  `{"value":{"$in":["ace","king"]}}`,
			"options": map[string]any{"limit": 2, "skip": 1, "sort": `{"_id":-1}`, "projection": `{"value":1}`},
		})
		require.NoError(mt, err)
		// Nested documents come back as plain maps, arrays as bson.A.
		assert.Equal(mt, map[string]any{"results": []map[string]any{
			{"_id": "c1", "stats": map[string]any{"hp": int32(35)}, "types": bson.A{"electric", int32(1)}},
			{"_id": "c2"},
		}}, got)

		name, cmd := sentCommand(mt)
		assert.Equal(mt, "find", name)
		assert.Equal(mt, testCollection, cmd["find"])
		assert.Equal(mt, bson.M{"value": bson.M{"$in": bson.A{"ace", "king"}}}, cmd["filter"])
		assert.Equal(mt, int64(2), cmd["limit"])
		assert.Equal(mt, int64(1), cmd["skip"])
		assert.Equal(mt, bson.M{"_id": int32(-1)}, cmd["sort"])
		assert.Equal(mt, bson.M{"value": int32(1)}, cmd["projection"])
	})

	mt.Run("no filter and no option sends an empty filter and nothing else", func(mt *mockT) {
		mt.AddMockResponses(firstBatch(testNamespace))

		got, err := run(mt, map[string]any{"type": "find"})
		require.NoError(mt, err)
		// No document at all is a nil list, not an empty one.
		assert.Equal(mt, map[string]any{"results": []map[string]any(nil)}, got)

		_, cmd := sentCommand(mt)
		assert.Equal(mt, bson.M{}, cmd["filter"])
		for _, key := range []string{"limit", "skip", "sort", "projection"} {
			assert.NotContains(mt, cmd, key)
		}
	})

	mt.Run("a sort on several keys reaches the find command in the written order", func(mt *mockT) {
		// AC 3 (#2039, D123): a find sorts on every key it is given, first key first. The single-key sort of the first
		// subtest is unchanged (AC 4).
		mt.AddMockResponses(firstBatch(testNamespace))

		_, err := run(mt, map[string]any{"type": "find", "options": map[string]any{"sort": `{"color": 1, "value": -1}`}})
		require.NoError(mt, err)

		command := sentRawCommand(mt)
		assert.Equal(mt, []string{"color", "value"}, orderedKeys(mt, command, "sort"))
		assert.Equal(mt, int32(1), command.Lookup("sort", "color").Int32())
		assert.Equal(mt, int32(-1), command.Lookup("sort", "value").Int32())
	})

	mt.Run("a server error is returned as is", func(mt *mockT) {
		mt.AddMockResponses(serverError())

		got, err := run(mt, map[string]any{"type": "find"})
		assert.EqualError(mt, err, serverErrorText)
		assert.Nil(mt, got)
	})

	mt.Run("a failing getMore fails the whole find, the first batch is lost", func(mt *mockT) {
		mt.AddMockResponses(
			cursorResponse(42, testNamespace, firstBatchKey, bson.D{{Key: "_id", Value: "c1"}}),
			serverError(),
		)

		got, err := run(mt, map[string]any{"type": "find"})
		assert.EqualError(mt, err, serverErrorText)
		assert.Nil(mt, got)

		names, _ := sentCommands(mt)
		assert.Equal(mt, []string{"find", "getMore"}, names[:2])
	})
}

func TestRunAction_update(t *testing.T) {
	mt := newMock(t)

	mt.Run("filter, update and upsert reach one multi update; the result is UpdateResult's fields", func(mt *mockT) {
		mt.AddMockResponses(successResponse(bson.E{Key: "n", Value: 2}, bson.E{Key: "nModified", Value: 1}))

		got, err := run(mt, map[string]any{
			"type":    "update",
			"filter":  `{"suit":"hearts"}`,
			"update":  `{"$set":{"value":"queen"}}`,
			"options": map[string]any{"upsert": true},
		})
		require.NoError(mt, err)
		assert.Equal(mt, map[string]any{
			"MatchedCount":  int64(2),
			"ModifiedCount": int64(1),
			"UpsertedCount": int64(0),
			"UpsertedID":    nil,
		}, got)

		name, cmd := sentCommand(mt)
		assert.Equal(mt, "update", name)
		assert.Equal(mt, testCollection, cmd["update"])
		assert.Equal(mt, bson.A{bson.M{
			"q":      bson.M{"suit": "hearts"},
			"u":      bson.M{"$set": bson.M{"value": "queen"}},
			"multi":  true,
			"upsert": true,
		}}, cmd["updates"])
	})

	mt.Run("an upsert reports the new _id and does not count it as matched", func(mt *mockT) {
		mt.AddMockResponses(successResponse(
			bson.E{Key: "n", Value: 1},
			bson.E{Key: "nModified", Value: 0},
			bson.E{Key: "upserted", Value: bson.A{bson.D{{Key: "index", Value: 0}, {Key: "_id", Value: "new-card"}}}},
		))

		got, err := run(mt, map[string]any{
			"type":    "update",
			"filter":  `{"_id":"new-card"}`,
			"update":  `{"$set":{"value":"joker"}}`,
			"options": map[string]any{"upsert": true},
		})
		require.NoError(mt, err)
		assert.Equal(mt, map[string]any{
			"MatchedCount":  int64(0),
			"ModifiedCount": int64(0),
			"UpsertedCount": int64(1),
			"UpsertedID":    "new-card",
		}, got)
	})

	mt.Run("no upsert option leaves the flag out; no filter matches everything", func(mt *mockT) {
		mt.AddMockResponses(successResponse(bson.E{Key: "n", Value: 0}, bson.E{Key: "nModified", Value: 0}))

		_, err := run(mt, map[string]any{"type": "update", "update": `{"$set":{"value":"two"}}`})
		require.NoError(mt, err)

		_, cmd := sentCommand(mt)
		updates, ok := cmd["updates"].(bson.A)
		require.True(mt, ok)
		require.Len(mt, updates, 1)
		assert.Equal(mt, bson.M{"q": bson.M{}, "u": bson.M{"$set": bson.M{"value": "two"}}, "multi": true}, updates[0])
	})

	mt.Run("an update document the driver refuses is an error before anything is sent", func(mt *mockT) {
		for _, tc := range []struct{ update, want string }{
			{update: "", want: "update document must have at least one element"},
			{update: `{"value":"queen"}`, want: "update document must contain key beginning with '$'"},
		} {
			got, err := run(mt, map[string]any{"type": "update", "filter": `{"suit":"hearts"}`, "update": tc.update})
			assert.EqualError(mt, err, tc.want, "update %q", tc.update)
			assert.Nil(mt, got)
		}
		assert.Empty(mt, mt.GetAllStartedEvents())
	})

	mt.Run("a server error is returned as is", func(mt *mockT) {
		mt.AddMockResponses(serverError())

		got, err := run(mt, map[string]any{"type": "update", "update": `{"$set":{"value":"two"}}`})
		assert.EqualError(mt, err, serverErrorText)
		assert.Nil(mt, got)
	})
}

